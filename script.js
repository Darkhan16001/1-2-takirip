function showPage(index) {
    if (index < 0 || index >= pages.length) {
        return;
    }

    // Бейнеблок басқа бетке өткенде
    // DOM-нан алынып, видео тоқтайды.

    currentStage = index;

    const content =
        document.getElementById("content");

    content.innerHTML = pages[index]();

    document.getElementById("stageLabel")
        .textContent = stages[index].title;

    document.getElementById("pageCounter")
        .textContent =
        (index + 1) + " / " + pages.length;

    document.getElementById("progressBar")
        .style.width =
        ((index + 1) / pages.length * 100) + "%";

    document.getElementById("previousBtn")
        .disabled = index === 0;

    const nextButton =
        document.getElementById("nextBtn");

    nextButton.disabled = index === pages.length - 1;

    nextButton.textContent =
        index === pages.length - 2
            ? "Қорытындыға өту →"
            : "Келесі бет →";

    renderNavigation();

    if (currentStage === 5) {
        const studentTextarea =
            document.getElementById("studentNames");

        if (studentTextarea) {
            studentTextarea.value = studentNamesText;
        }
    }

    if (currentStage === 7) {
        renderConclusionScores();
    }

    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });
}

