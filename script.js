document.addEventListener("click", function (event) {
    const stageButton =
        event.target.closest("[data-stage]");

    if (stageButton) {
        const stageIndex = Number(
            stageButton.dataset.stage
        );

        showPage(stageIndex);
        return;
    }

    const revealButton =
        event.target.closest("[data-reveal]");

    if (revealButton) {
        const answerID =
            revealButton.dataset.reveal;

        const answer =
            document.getElementById(answerID);

        if (!answer) return;

        answer.classList.toggle("visible");

        revealButton.textContent =
            answer.classList.contains("visible")
                ? "Жауапты жасыру"
                : "Жауабын көрсету";

        return;
    }

    const scoreButton =
        event.target.closest("[data-team][data-points]");

    if (scoreButton) {
        const teamIndex = Number(
            scoreButton.dataset.team
        );

        const points = Number(
            scoreButton.dataset.points
        );

        addScore(teamIndex, points);
        return;
    }

    const studentButton =
        event.target.closest("#pickStudent");

    if (studentButton) {
        pickStudent();
        return;
    }
});

