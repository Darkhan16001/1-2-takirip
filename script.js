const teams = [
    { name: "1-команда", score: 0 },
    { name: "2-команда", score: 0 },
    { name: "3-команда", score: 0 }
];

function updateScores() {
    const scoreContainer =
        document.getElementById("sidebarScores");

    scoreContainer.innerHTML = teams.map(team => `
        <div class="score-row">
            <span>${team.name}</span>
            <strong>${team.score} ұпай</strong>
        </div>
    `).join("");

    if (currentStage === 7) {
        renderConclusionScores();
    }
}

function addScore(teamIndex, points) {
    const team = teams[teamIndex];

    if (!team) return;

    team.score = Math.max(
        0,
        team.score + points
    );

    updateScores();
}

function resetScores() {
    if (!confirm("Барлық командалардың ұпайын нөлдейміз бе?")) {
        return;
    }

    teams.forEach(team => {
        team.score = 0;
    });

    updateScores();
}

document.getElementById("resetScores")
    .addEventListener("click", resetScores);

