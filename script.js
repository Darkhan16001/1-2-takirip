function pickStudent() {
    const textarea =
        document.getElementById("studentNames");

    if (!textarea) return;

    const raw = textarea.value.trim();

    if (!raw) {
        document.getElementById("studentResult")
            .textContent =
            "Алдымен студенттердің есімдерін жазыңдар.";

        return;
    }

    if (raw !== studentNamesText) {
        studentNamesText = raw;

        unusedStudents = raw
            .split(/[,;\n]+/)
            .map(name => name.trim())
            .filter(Boolean);
    }

    if (unusedStudents.length === 0) {
        unusedStudents = studentNamesText
            .split(/[,;\n]+/)
            .map(name => name.trim())
            .filter(Boolean);
    }

    if (unusedStudents.length === 0) return;

    const randomIndex = Math.floor(
        Math.random() * unusedStudents.length
    );

    const selected =
        unusedStudents.splice(randomIndex, 1)[0];

    document.getElementById("studentResult")
        .textContent = "Таңдалған студент: " + selected;
}

